def write(path: Path, content: str, overwrite: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not overwrite:
        print(f"  keep   {path}")
        return
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"  write  {path}")


def service_block(name, port, redis_db, uses_pg) -> str:
    env = [
        f"SERVICE_NAME={name}",
        "LOG_LEVEL=INFO",
        f"REDIS_URL=redis://redis:6379/{redis_db}",
        "KAFKA_BOOTSTRAP_SERVERS=kafka:9092",
    ]
    if uses_pg:
        env.insert(
            0,
            "DATABASE_URL=postgresql+asyncpg://meridian:"
            "${POSTGRES_PASSWORD:-meridian_dev}@postgres:5432/meridian",
        )
    env += EXTRA_ENV.get(name, [])
    env_lines = "\n".join(f"      - {e}" for e in env)

    deps = ["      redis:\n        condition: service_healthy"]
    if uses_pg:
        deps.insert(0, "      postgres:\n        condition: service_healthy")
    deps_lines = "\n".join(deps)

    return f"""\
  {name}:
    build: ./services/{name}
    environment:
{env_lines}
    ports:
      - "{port}:8000"
    depends_on:
{deps_lines}
    volumes:
      - ./services/{name}:/app
      - ./shared:/shared:ro
{HEALTHCHECK}
"""


