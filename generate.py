def build_kong() -> str:
    out = ['_format_version: "3.0"', "", "services:"]
    for name, _, _, _, path in SERVICES:
        out += [
            f"  - name: {name}",
            f"    url: http://{name}:8000",
            "    routes:",
            f"      - name: {name}-route",
            f'        paths: ["{path}"]',
            "        strip_path: true",
        ]
    out += [
        "",
        "# Dev-only CORS: restrict origins before any real deployment.",
        "plugins:",
        "  - name: cors",
        "    config:",
        '      origins: ["*"]',
        '      methods: ["GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"]',
        '      headers: ["Accept", "Authorization", "Content-Type"]',
        "      max_age: 3600",
        "",
    ]
    return "\n".join(out)


