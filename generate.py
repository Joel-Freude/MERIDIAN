INIT_SQL = "CREATE EXTENSION IF NOT EXISTS postgis;\n"


def main() -> None:
    root = Path(".")
    print("Generating services:")
    for name, *_ in SERVICES:
        base = root / "services" / name
        write(base / "Dockerfile", DOCKERFILE)
        write(base / "requirements.txt", REQUIREMENTS)
        write(base / "main.py", MAIN_PY.format(name=name))
        write(base / ".dockerignore", DOCKERIGNORE)

    print("Generating gateway, infra, shared, compose:")
    write(root / "services/api-gateway/kong.yml", build_kong(), overwrite=True)
    write(root / "infra/init-db/01-init.sql", INIT_SQL)
    write(root / "infra/prometheus/prometheus.yml", PROMETHEUS)
    write(root / "shared/.gitkeep", "")
    write(root / ".env.example", ENV_EXAMPLE)
    write(root / "docker-compose.microservices.yml", build_compose(), overwrite=True)
    print("Done.")


if __name__ == "__main__":
    main()
